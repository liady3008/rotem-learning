/**
 * Value of an addition/subtraction exercise with directed numbers, written as in the exercises:
 * first number may be negative without brackets, later negative numbers in brackets. Example: "-2 - (-7)".
 * Answers are computed from the exercise text so they cannot drift from it.
 */
export function calc(expr: string): number {
  const s = expr.replace(/\s+/g, '');
  const term = String.raw`(?:\d+|\(-?\d+\))`;
  if (!new RegExp(`^(?:-?\\d+|${term})(?:[+-]${term})*$`).test(s)) throw new Error(`bad exercise: ${expr}`);
  const val = (t: string): number => Number(t.replace(/[()]/g, ''));
  const head = /^(-?\d+|\(-?\d+\))/.exec(s)![0];
  let total = val(head);
  for (const m of s.slice(head.length).matchAll(/([+-])(\d+|\(-?\d+\))/g)) total += m[1] === '+' ? val(m[2]) : -val(m[2]);
  return total;
}

